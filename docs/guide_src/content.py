def B(label: str) -> str:
    """Inline bot button label."""
    return f'<span class="btn">{html.escape(label)}</span>'


def C(s: str) -> str:
    return f"<code>{html.escape(s)}</code>"


def F(name: str) -> str:
    """A Persian output file name, shown LTR-isolated like a real file name (LRM keeps the Latin date in order)."""
    safe = re.sub(r"(?<![0-9])([0-9])", "\u200e\\1", html.escape(name))
    return '<span class="btn" dir="ltr" style="background:#f3f6ea;border-color:#b9c98f;direction:ltr;unicode-bidi:isolate">' + safe + "</span>"


